package server

import (
	"net"
	"testing"
)

// freeLocalAddr returns a free local address for testing
// This is only needed in integration tests where we need real network listeners
func freeLocalAddr(t *testing.T) string {
	t.Helper()
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatalf("listen: %v", err)
	}
	addr := l.Addr().String()
	_ = l.Close()
	return addr
}
