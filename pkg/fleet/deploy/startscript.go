// RenderStartScript renders the nohup fallback start script used when
// systemd is unavailable. The script is idempotent: rerunning it will
// terminate the previous daemon (if any) and relaunch it detached
// from the SSH session.
//
// The script lives at $HOME/<install-dir>/start-quicbaas-agent.sh on
// the remote and logs to $HOME/<data-dir>/agent.log so operators can
// tail it post-deploy.
func RenderStartScript(spec *Spec) string {
	// Shell scripts use $HOME (shell-supplied) rather than systemd's %h.
	//
	// Every path goes through shellQuotePath, which leaves the leading $HOME
	// outside the quotes: a single-quoted '$HOME/...' is a literal directory
	// named "$HOME", which is where this script used to write its pid file.
	args := fleetServeArgs(spec, "$HOME")
	layout := spec.Layout("$HOME")
	bin := shellQuotePath(layout.Binary)
	dataDir := layout.DataDir
	logFile := layout.LogFile
	pidFile := layout.PIDFile

	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# QuicBaaS agent launcher (nohup fallback).\n")
	b.WriteString("# Generated by pkg/fleet/deploy; do not edit by hand.\n")
	b.WriteString("set -eu\n")
	b.WriteString("mkdir -p ")
	b.WriteString(shellQuotePath(dataDir))
	b.WriteString("\n")
	b.WriteString("if [ -f ")
	b.WriteString(shellQuotePath(pidFile))
	b.WriteString(" ]; then\n")
	b.WriteString("  OLDPID=$(cat ")
	b.WriteString(shellQuotePath(pidFile))
	b.WriteString(" 2>/dev/null || true)\n")
	b.WriteString("  if [ -n \"${OLDPID:-}\" ] && kill -0 \"$OLDPID\" 2>/dev/null; then\n")
	b.WriteString("    kill \"$OLDPID\" || true\n")
	b.WriteString("    sleep 1\n")
	b.WriteString("    kill -0 \"$OLDPID\" 2>/dev/null && kill -9 \"$OLDPID\" || true\n")
	b.WriteString("  fi\n")
	b.WriteString("  rm -f ")
	b.WriteString(shellQuotePath(pidFile))
	b.WriteString("\n")
	b.WriteString("fi\n")
	b.WriteString("nohup ")
	b.WriteString(bin)
	b.WriteString(" ")
	b.WriteString(strings.Join(args, " "))
	b.WriteString(" >> ")
	b.WriteString(shellQuotePath(logFile))
	b.WriteString(" 2>&1 &\n")
	b.WriteString("echo $! > ")
	b.WriteString(shellQuotePath(pidFile))
	b.WriteString("\n")
	return b.String()
}

// StartBackground uploads the rendered script to scriptPath, marks it
// executable, and runs it. scriptPath should be an absolute path (or
// use $HOME expansion) that the caller already reserved on the remote.
func StartBackground(ctx context.Context, target Target, scriptContent, scriptPath string) error {
	if target == nil {
		return &RemoteExecError{Command: "start " + scriptPath, Cause: errClosed}
	}
	if scriptPath == "" {
		return &InvalidSpecError{Field: "script_path", Reason: "script path is required"}
	}

	// Ensure the containing directory exists.
	if dir := path.Dir(scriptPath); dir != "" && dir != "." && dir != "/" {
		if _, _, err := target.Exec(ctx, "mkdir -p "+shellQuote(dir)); err != nil {
			return err
		}
	}

	if err := target.WriteFile(ctx, scriptPath, []byte(scriptContent), 0o755); err != nil {
		return err
	}

	// Invoke via sh -c so $HOME expansions in the script body resolve
	// on the login shell. We do not tail the log here; the service
	// layer polls the control plane registry to confirm liveness.
	if _, _, err := target.Exec(ctx, "sh "+shellQuote(scriptPath)); err != nil {
		return err
	}
	return nil
}
