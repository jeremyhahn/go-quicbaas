// Package uicontract holds the contract test that compares the TypeScript
// SDK's hand-written response types against the Go structs the server
// actually serialises.
//
// WHY THIS PACKAGE EXISTS. Nothing in the build compared the two. The Go
// structs are generated by nobody and mirrored by hand in
// sdk/typescript/src/types.ts, and a mirror that drifts still compiles: the
// browser reads `session.last_active`, TypeScript confirms the field is
// declared, and at runtime the server sent `last_activity`. The column
// renders an em-dash forever and every layer reports success. Three such
// fields shipped and were found by a person looking at a screen
// (go-quicbaas#856, go-quicbaas#855).
//
// The Go structs are the honest source. They are what `encoding/json` writes
// onto the wire; the TypeScript types are a claim about that wire, and the
// frontend store's own interfaces are a second claim about the first. So the
// test reflects over the Go structs — exact, not parsed — and reads the
// TypeScript as text.
//
// The package carries NO build tag on purpose. A contract test that some
// build pass omits is a contract nothing checks.
package uicontract
