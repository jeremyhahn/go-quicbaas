//go:build unix

package workerimage

import (
	"os"
	"syscall"
)

// fileOwner returns the uid that owns path on this host.
func fileOwner(path string) (int, error) {
	info, err := os.Stat(path)
	if err != nil {
		return 0, err
	}
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, &UnsupportedPlatformError{What: "file ownership"}
	}
	return int(stat.Uid), nil
}
