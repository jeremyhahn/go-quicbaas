// TestSecretSpecEqual covers Equal across the nil-handling branches that
// EnsureSecret relies on to decide whether a stored spec matches the
// requested one.
func TestSecretSpecEqual(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		a    *SecretSpec
		b    *SecretSpec
		want bool
	}{
		{name: "both_nil", a: nil, b: nil, want: true},
		{name: "left_nil", a: nil, b: &SecretSpec{Length: 1, Encoding: EncodingHex}, want: false},
		{name: "right_nil", a: &SecretSpec{Length: 1, Encoding: EncodingHex}, b: nil, want: false},
		{
			name: "equal",
			a:    &SecretSpec{Length: 16, Encoding: EncodingBase64},
			b:    &SecretSpec{Length: 16, Encoding: EncodingBase64},
			want: true,
		},
		{
			name: "length_differs",
			a:    &SecretSpec{Length: 16, Encoding: EncodingBase64},
			b:    &SecretSpec{Length: 32, Encoding: EncodingBase64},
			want: false,
		},
		{
			name: "encoding_differs",
			a:    &SecretSpec{Length: 16, Encoding: EncodingBase64},
			b:    &SecretSpec{Length: 16, Encoding: EncodingHex},
			want: false,
		},
	}

	for _, tc := range tests {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			assert.Equal(t, tc.want, tc.a.Equal(tc.b))
		})
	}
}

// TestSecretSpecGenerateInvalid covers Generate's early-return when the
// spec fails validation. No bytes are produced for a malformed spec.
func TestSecretSpecGenerateInvalid(t *testing.T) {
	t.Parallel()

	spec := &SecretSpec{Length: 0, Encoding: EncodingHex}
	got, err := spec.Generate()
	require.Error(t, err)
	assert.ErrorIs(t, err, ErrInvalidSpec)
	assert.Nil(t, got)
}

// TestSecretSpecGenerateEncodings covers the happy-path generation for
// every supported encoding, asserting the documented length semantics.
func TestSecretSpecGenerateEncodings(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		spec     *SecretSpec
		wantLen  int // expected stored byte length, -1 means "just non-empty"
		validate func(t *testing.T, out []byte)
	}{
		{
			name:    "numeric_digits",
			spec:    &SecretSpec{Length: 6, Encoding: EncodingNumeric},
			wantLen: 6,
			validate: func(t *testing.T, out []byte) {
				for _, c := range out {
					require.True(t, c >= '0' && c <= '9', "non-digit byte %q", c)
				}
			},
		},
		{
			name:    "raw_exact",
			spec:    &SecretSpec{Length: 8, Encoding: EncodingRaw},
			wantLen: 8,
		},
		{
			name:    "hex_doubles",
			spec:    &SecretSpec{Length: 4, Encoding: EncodingHex},
			wantLen: 8,
		},
		{
			name:    "base64_nonempty",
			spec:    &SecretSpec{Length: 16, Encoding: EncodingBase64},
			wantLen: -1,
		},
	}

	for _, tc := range tests {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			out, err := tc.spec.Generate()
			require.NoError(t, err)
			if tc.wantLen >= 0 {
				assert.Len(t, out, tc.wantLen)
			} else {
				assert.NotEmpty(t, out)
			}
			if tc.validate != nil {
				tc.validate(t, out)
			}
		})
	}
}

// TestSpecFromMetadata covers every branch of metadata parsing: the
// not-auto-generated short circuits and each malformed-metadata error.
func TestSpecFromMetadata(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		meta     map[string]string
		wantSpec *SecretSpec
		wantErr  bool
	}{
		{
			name:     "nil_metadata",
			meta:     nil,
			wantSpec: nil,
		},
		{
			name:     "not_auto_generated",
			meta:     map[string]string{"some": "value"},
			wantSpec: nil,
		},
		{
			name: "missing_length",
			meta: map[string]string{
				MetaAutoGenerated: "true",
				MetaSpecEncoding:  EncodingHex,
			},
			wantErr: true,
		},
		{
			name: "non_numeric_length",
			meta: map[string]string{
				MetaAutoGenerated: "true",
				MetaSpecLength:    "not-a-number",
				MetaSpecEncoding:  EncodingHex,
			},
			wantErr: true,
		},
		{
			name: "missing_encoding",
			meta: map[string]string{
				MetaAutoGenerated: "true",
				MetaSpecLength:    "16",
			},
			wantErr: true,
		},
		{
			name: "invalid_stored_spec",
			meta: map[string]string{
				MetaAutoGenerated: "true",
				MetaSpecLength:    "-5",
				MetaSpecEncoding:  EncodingHex,
			},
			wantErr: true,
		},
		{
			name: "valid",
			meta: map[string]string{
				MetaAutoGenerated: "true",
				MetaSpecLength:    "16",
				MetaSpecEncoding:  EncodingBase64,
			},
			wantSpec: &SecretSpec{Length: 16, Encoding: EncodingBase64},
		},
	}

	for _, tc := range tests {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			spec, err := specFromMetadata(tc.meta)
			if tc.wantErr {
				require.Error(t, err)
				assert.Nil(t, spec)
				return
			}
			require.NoError(t, err)
			assert.Equal(t, tc.wantSpec, spec)
		})
	}
}

// TestSpecToMetadata covers the merge path that copies caller-supplied
// metadata alongside the spec markers — the caller-meta loop is only
// exercised when callerMeta is non-empty.
func TestSpecToMetadata(t *testing.T) {
	t.Parallel()

	spec := &SecretSpec{Length: 24, Encoding: EncodingNumeric}
	caller := map[string]string{"team": "platform", "env": "prod"}

	merged := specToMetadata(spec, caller)

	assert.Equal(t, "platform", merged["team"])
	assert.Equal(t, "prod", merged["env"])
	assert.Equal(t, "true", merged[MetaAutoGenerated])
	assert.Equal(t, "24", merged[MetaSpecLength])
	assert.Equal(t, EncodingNumeric, merged[MetaSpecEncoding])

	// A round-trip through specFromMetadata must recover the spec.
	got, err := specFromMetadata(merged)
	require.NoError(t, err)
	assert.True(t, spec.Equal(got))
}

// TestSpecToMetadataNilCaller covers the nil caller-metadata case, which
// must still yield a well-formed metadata map carrying the markers.
func TestSpecToMetadataNilCaller(t *testing.T) {
	t.Parallel()

	spec := &SecretSpec{Length: 12, Encoding: EncodingRaw}
	merged := specToMetadata(spec, nil)

	assert.Equal(t, "true", merged[MetaAutoGenerated])
	assert.Equal(t, "12", merged[MetaSpecLength])
	assert.Equal(t, EncodingRaw, merged[MetaSpecEncoding])
}
