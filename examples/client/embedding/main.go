// Example: Embedding and RAG (Retrieval-Augmented Generation)
//
// This example demonstrates:
// - Vector storage and retrieval operations
// - Embedding generation and indexing (simulated embeddings)
// - Semantic search/similarity queries
// - Complete RAG workflow: store documents, query for relevant chunks
//
// In a production system, embeddings would typically be generated by an
// external model (OpenAI, Cohere, sentence-transformers, etc.). This example
// uses simulated embeddings to demonstrate the QuicBaaS vector operations.
//
// Prerequisites:
// - A running QuicBaaS server (default: localhost:50051)
// - Server must be initialized and unsealed
//
// Usage:
//
//	# Run with default gRPC transport
//	go run main.go
//
//	# Run with REST transport
//	go run main.go -transport rest -address http://localhost:8080
//
//	# Run with QUIC transport
//	go run main.go -transport quic -address localhost:50052
package main

import (
	"context"
	"flag"
	"fmt"
	"hash/fnv"
	"log"
	"math"
	"strings"
	"time"

	quicbaas "github.com/jeremyhahn/go-quicbaas/sdk/go"
	"github.com/jeremyhahn/go-quicbaas/sdk/go/client/vector"
)

// Document represents a text document to be stored and searched.
type Document struct {
	ID       string
	Title    string
	Content  string
	Category string
}

// EmbeddingDimension is the size of our simulated embedding vectors.
// Common dimensions in production: 384 (MiniLM), 768 (BERT), 1536 (OpenAI ada-002).
const EmbeddingDimension = 128

func main() {
	// Parse command-line flags
	transportType := flag.String("transport", "grpc", "Transport protocol (grpc, rest, quic)")
	address := flag.String("address", "localhost:50051", "Server address")
	flag.Parse()

	fmt.Println("=== QuicBaaS Embedding/RAG Example ===")
	fmt.Printf("Transport: %s\n", *transportType)
	fmt.Printf("Address:   %s\n", *address)
	fmt.Println()

	// Create client with the specified transport
	var opts []quicbaas.Option
	opts = append(opts, quicbaas.WithTimeout(30*time.Second))
	// Select transport based on flag
	switch *transportType {
	case "rest":
		opts = append(opts, quicbaas.WithREST())
	case "quic":
		opts = append(opts, quicbaas.WithQUIC())
		// default is gRPC, no option needed
	}

	client, err := quicbaas.NewClient(*address, opts...)
	if err != nil {
		log.Fatalf("Failed to create client: %v", err)
	}
	defer func() {
		if closeErr := client.Close(); closeErr != nil {
			log.Printf("Warning: failed to close client: %v", closeErr)
		}
	}()

	ctx := context.Background()

	// Define sample documents for our knowledge base
	documents := []Document{
		{
			ID:       "doc-1",
			Title:    "Introduction to Machine Learning",
			Content:  "Machine learning is a subset of artificial intelligence that enables systems to learn and improve from experience without being explicitly programmed. It focuses on developing algorithms that can access data and use it to learn for themselves.",
			Category: "ai",
		},
		{
			ID:       "doc-2",
			Title:    "Deep Learning Fundamentals",
			Content:  "Deep learning is a type of machine learning based on artificial neural networks with multiple layers. These networks can learn hierarchical representations of data, enabling them to solve complex problems like image recognition and natural language processing.",
			Category: "ai",
		},
		{
			ID:       "doc-3",
			Title:    "Database Indexing Strategies",
			Content:  "Database indexing is a data structure technique used to quickly locate and access data in a database. Indexes are created using B-trees, hash tables, or other structures to improve query performance and reduce disk I/O operations.",
			Category: "database",
		},
		{
			ID:       "doc-4",
			Title:    "Distributed Systems Basics",
			Content:  "Distributed systems are collections of independent computers that appear to users as a single coherent system. They provide fault tolerance, scalability, and geographic distribution of resources across multiple nodes.",
			Category: "systems",
		},
		{
			ID:       "doc-5",
			Title:    "Vector Databases for AI",
			Content:  "Vector databases are specialized databases designed to store and query high-dimensional vector embeddings. They use approximate nearest neighbor algorithms like HNSW or IVF to enable fast similarity search for AI applications.",
			Category: "ai",
		},
		{
			ID:       "doc-6",
			Title:    "Consensus Algorithms",
			Content:  "Consensus algorithms like Raft and Paxos enable distributed systems to agree on a single value even when some nodes fail. They are fundamental to building reliable distributed databases and coordination services.",
			Category: "systems",
		},
		{
			ID:       "doc-7",
			Title:    "Natural Language Processing",
			Content:  "Natural language processing combines computational linguistics with machine learning to enable computers to understand, interpret, and generate human language. Key techniques include tokenization, embeddings, and transformer models.",
			Category: "ai",
		},
		{
			ID:       "doc-8",
			Title:    "Key-Value Store Architecture",
			Content:  "Key-value stores are NoSQL databases that use a simple key-value pair model for data storage. They offer high performance for read and write operations, making them ideal for caching, session management, and real-time applications.",
			Category: "database",
		},
	}

	// Namespace for our knowledge base vectors
	namespace := "knowledge-base"

	// Step 1: Index documents (generate embeddings and store)
	fmt.Println("Step 1: Indexing documents with embeddings...")
	fmt.Printf("  Namespace: %s\n", namespace)
	fmt.Printf("  Embedding dimension: %d\n", EmbeddingDimension)
	fmt.Println()

	for _, doc := range documents {
		// Generate embedding from document content
		// In production, you would use an embedding model like OpenAI, Cohere, etc.
		embedding := generateEmbedding(doc.Content)

		// Upsert vector with metadata
		resp, upsertErr := client.Vector().Upsert(ctx, &vector.UpsertRequest{
			Vector: &vector.VectorEntity{
				ID:        doc.ID,
				Namespace: namespace,
				Vector:    embedding,
				Metadata: map[string]string{
					"title":    doc.Title,
					"content":  doc.Content,
					"category": doc.Category,
				},
			},
		})
		if upsertErr != nil {
			log.Fatalf("Failed to upsert document %s: %v", doc.ID, upsertErr)
		}
		fmt.Printf("  Indexed: %s - %s\n", resp.ID, doc.Title)
	}

	// Step 2: Semantic search - find documents similar to a query
	fmt.Println("\nStep 2: Performing semantic search...")
	query := "How do neural networks learn from data?"
	fmt.Printf("  Query: \"%s\"\n", query)

	// Generate query embedding
	queryEmbedding := generateEmbedding(query)

	// Search for similar documents
	searchResp, err := client.Vector().SearchSimilar(ctx, &vector.SearchSimilarRequest{
		Namespace:       namespace,
		QueryVector:     queryEmbedding,
		K:               3,
		IncludeVectors:  false,
		IncludeMetadata: true,
	})
	if err != nil {
		log.Fatalf("Failed to search: %v", err)
	}

	fmt.Printf("\n  Top %d results:\n", len(searchResp.Results))
	for i, result := range searchResp.Results {
		title := result.Vector.Metadata["title"]
		fmt.Printf("    %d. [Score: %.4f] %s (ID: %s)\n", i+1, result.Score, title, result.Vector.ID)
	}

	// Step 3: Semantic search with metadata filter (using HybridSearch)
	fmt.Println("\nStep 3: Filtered semantic search (category: ai)...")
	systemsQuery := "How do computers coordinate with each other?"
	fmt.Printf("  Query: \"%s\"\n", systemsQuery)

	systemsEmbedding := generateEmbedding(systemsQuery)

	filteredResp, err := client.Vector().HybridSearch(ctx, &vector.HybridSearchRequest{
		Namespace:   namespace,
		QueryVector: systemsEmbedding,
		K:           3,
		MetadataFilters: []*vector.MetadataFilter{
			{
				Key:      "category",
				Operator: vector.FilterOperatorEquals,
				Value:    "ai",
			},
		},
		IncludeMetadata: true,
	})
	if err != nil {
		log.Fatalf("Failed to perform filtered search: %v", err)
	}

	fmt.Printf("\n  Top %d AI-filtered results:\n", len(filteredResp.Results))
	for i, result := range filteredResp.Results {
		title := result.Vector.Metadata["title"]
		category := result.Vector.Metadata["category"]
		fmt.Printf("    %d. [Score: %.4f] %s (Category: %s)\n", i+1, result.Score, title, category)
	}

	// Step 4: RAG workflow demonstration
	fmt.Println("\nStep 4: Complete RAG workflow...")
	ragQuery := "What are the best practices for storing AI embeddings?"
	fmt.Printf("  User question: \"%s\"\n", ragQuery)

	// Step 4a: Retrieve relevant context
	ragEmbedding := generateEmbedding(ragQuery)

	ragResults, err := client.Vector().SearchSimilar(ctx, &vector.SearchSimilarRequest{
		Namespace:       namespace,
		QueryVector:     ragEmbedding,
		K:               2,
		IncludeMetadata: true,
	})
	if err != nil {
		log.Fatalf("Failed to retrieve context: %v", err)
	}

	fmt.Println("\n  Retrieved context documents:")
	var contextChunks []string
	for i, result := range ragResults.Results {
		title := result.Vector.Metadata["title"]
		content := result.Vector.Metadata["content"]
		fmt.Printf("    Context %d: %s\n", i+1, title)
		contextChunks = append(contextChunks, content)
	}

	// Step 4b: Build prompt with context (simulated)
	fmt.Println("\n  Building augmented prompt for LLM:")
	fmt.Println("  --------------------------------")
	fmt.Println("  System: You are a helpful assistant. Use the following context to answer the question.")
	fmt.Println()
	fmt.Println("  Context:")
	for i, chunk := range contextChunks {
		// Truncate for display
		displayContent := chunk
		if len(displayContent) > 100 {
			displayContent = displayContent[:100] + "..."
		}
		fmt.Printf("    [%d] %s\n", i+1, displayContent)
	}
	fmt.Println()
	fmt.Printf("  Question: %s\n", ragQuery)
	fmt.Println("  --------------------------------")
	fmt.Println()
	fmt.Println("  [In production, this prompt would be sent to an LLM for generation]")

	// Step 5: Search with different queries to demonstrate semantic understanding
	fmt.Println("\nStep 5: Demonstrating semantic understanding...")

	queries := []string{
		"How can I make my database queries faster?",
		"What is the difference between ML and DL?",
		"How do nodes in a cluster reach agreement?",
	}

	for _, q := range queries {
		qEmbed := generateEmbedding(q)
		qResp, searchErr := client.Vector().SearchSimilar(ctx, &vector.SearchSimilarRequest{
			Namespace:       namespace,
			QueryVector:     qEmbed,
			K:               1,
			IncludeMetadata: true,
		})
		if searchErr != nil {
			log.Printf("  Warning: Search failed for query '%s': %v", q, searchErr)
			continue
		}

		if len(qResp.Results) > 0 {
			bestMatch := qResp.Results[0]
			title := bestMatch.Vector.Metadata["title"]
			fmt.Printf("  Query: \"%s\"\n", q)
			fmt.Printf("    Best match: %s (Score: %.4f)\n\n", title, bestMatch.Score)
		}
	}

	// Step 6: Delete a document
	fmt.Println("Step 6: Deleting a document...")
	deleteID := "doc-8"
	deleteResp, err := client.Vector().Delete(ctx, &vector.DeleteRequest{
		Namespace: namespace,
		ID:        deleteID,
	})
	if err != nil {
		log.Fatalf("Failed to delete document: %v", err)
	}
	if deleteResp.Deleted {
		fmt.Printf("  Deleted document: %s\n", deleteID)
	}

	// Step 7: Verify deletion by searching
	fmt.Println("\nStep 7: Verifying deletion (searching for key-value stores)...")
	kvQuery := "key-value store caching"
	kvEmbed := generateEmbedding(kvQuery)

	verifyResp, err := client.Vector().SearchSimilar(ctx, &vector.SearchSimilarRequest{
		Namespace:       namespace,
		QueryVector:     kvEmbed,
		K:               3,
		IncludeMetadata: true,
	})
	if err != nil {
		log.Fatalf("Failed to verify search: %v", err)
	}

	fmt.Printf("  Search results for \"%s\":\n", kvQuery)
	for i, result := range verifyResp.Results {
		title := result.Vector.Metadata["title"]
		fmt.Printf("    %d. %s (Score: %.4f)\n", i+1, title, result.Score)
	}
	fmt.Println("  (Key-Value Store Architecture should not appear)")

	// Step 8: Cleanup - delete all remaining documents
	fmt.Println("\nStep 8: Cleaning up remaining documents...")
	for _, doc := range documents {
		if doc.ID == deleteID {
			continue // Already deleted
		}
		delResp, delErr := client.Vector().Delete(ctx, &vector.DeleteRequest{
			Namespace: namespace,
			ID:        doc.ID,
		})
		if delErr != nil {
			log.Printf("  Warning: Failed to delete %s: %v", doc.ID, delErr)
		} else if delResp.Deleted {
			fmt.Printf("  Deleted: %s\n", doc.ID)
		}
	}

	fmt.Println("\n=== Example Complete ===")
	fmt.Println("\nKey Takeaways:")
	fmt.Println("  1. Vector operations enable semantic search on unstructured data")
	fmt.Println("  2. Embeddings capture semantic meaning of text for similarity matching")
	fmt.Println("  3. Metadata filtering allows combining semantic search with traditional queries")
	fmt.Println("  4. RAG workflow: Retrieve context -> Augment prompt -> Generate response")
	fmt.Println("  5. QuicBaaS's vector client provides Upsert, SearchSimilar, and Delete operations")
	fmt.Println("  6. Namespaces organize vectors by use case (knowledge-base, products, etc.)")
	fmt.Println("  7. K parameter controls how many similar results to return")
	fmt.Println("  8. The SDK supports multiple transports (gRPC, REST, QUIC)")
}

// generateEmbedding creates a simulated embedding vector from text.
// In production, you would use an embedding model (OpenAI, Cohere, HuggingFace, etc.)
//
// This simulation uses a deterministic hash-based approach to create
// consistent embeddings that capture some basic text characteristics.
// It is NOT suitable for production use.
func generateEmbedding(text string) []float32 {
	// Normalize text
	text = strings.ToLower(text)
	words := strings.Fields(text)

	// Initialize embedding with zeros
	embedding := make([]float32, EmbeddingDimension)

	// Use FNV hash to create deterministic pseudo-random values
	hasher := fnv.New64a()

	// Generate base embedding from word hashes
	for _, word := range words {
		hasher.Reset()
		hasher.Write([]byte(word))
		hash := hasher.Sum64()

		// Distribute word influence across embedding dimensions
		for i := range EmbeddingDimension {
			// Create deterministic but varied contribution per dimension
			dimHash := hash ^ uint64(i*31)
			contribution := float32(dimHash%1000) / 1000.0
			if dimHash%2 == 0 {
				contribution = -contribution
			}
			embedding[i] += contribution
		}
	}

	// Add positional information (early words influence early dimensions more)
	for i, word := range words {
		if i >= EmbeddingDimension {
			break
		}
		hasher.Reset()
		hasher.Write([]byte(word))
		hash := hasher.Sum64()
		positional := float32(hash%500) / 1000.0
		embedding[i] += positional * (1.0 - float32(i)/float32(len(words)))
	}

	// Normalize to unit vector (L2 normalization)
	var norm float32
	for _, v := range embedding {
		norm += v * v
	}
	norm = float32(math.Sqrt(float64(norm)))

	if norm > 0 {
		for i := range embedding {
			embedding[i] /= norm
		}
	}

	return embedding
}
