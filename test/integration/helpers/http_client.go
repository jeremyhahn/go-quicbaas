//go:build integration

package helpers

import (
	"crypto/tls"
	"net"
	"net/http"
	"time"
)

// NewHTTPClient returns an HTTP client configured for integration tests.
// It accepts self-signed TLS certificates (InsecureSkipVerify) and uses
// the specified timeout.
func NewHTTPClient(timeout time.Duration) *http.Client {
	return &http.Client{
		Timeout: timeout,
		Transport: &http.Transport{
			TLSClientConfig: &tls.Config{
				InsecureSkipVerify: true, //#nosec G402 -- integration tests use self-signed certs
			},
			TLSHandshakeTimeout: 10 * time.Second,
			DialContext: (&net.Dialer{
				Timeout:   10 * time.Second,
				KeepAlive: 30 * time.Second,
			}).DialContext,
		},
	}
}
