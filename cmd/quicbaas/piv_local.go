// piv_local.go provides the client-LOCAL PIV material access used by the
// canonical "auth factor add --type piv" and "auth login --method piv"
// commands.
//
// PIV login proves possession of a key held by THIS client, so — like the
// Devices() CTAP2 helper and xkmsctl's --protocol embedded mode — the CLI
// runs the go-xkms PIV backends in-process instead of routing a transport
// verb to the server. The remote Security().Auth().PIV() surface manages the
// SERVER's PIV slots and is not used here. There is no PC/SC reader model in
// go-xkms: local PIV material lives in the file (software), pkcs11, or tpm2
// backends; physical smart cards are reachable through the pkcs11 backend
// (e.g. YubiKey via ykcs11).
//
// All construction goes through go-xkms sdk/go entry points — the same ones
// xkey's PIV commands use — so no xkms logic is duplicated here.
package main

import (
	"context"
	"crypto/x509"
	"path/filepath"
	"strings"

	xkmssdk "github.com/jeremyhahn/go-xkms/sdk/go"
)

// Canonical --piv-backend flag values.
const (
	localPIVBackendFile   = "file"
	localPIVBackendPKCS11 = "pkcs11"
	localPIVBackendTPM2   = "tpm2"
)

// localPIVXKMSBackendName is the xkms backend name the file-backed local
// PIV session registers its software keystore under. It matches xkey's
// software PIV backend naming so ParseStoreType resolves cleanly and key
// material generated by xkey interoperates.
const localPIVXKMSBackendName = "software"

// defaultLocalPIVDir is the default root for file-backed local PIV
// material: keys under the directory itself, PIV certificates under
// <dir>/piv.
const defaultLocalPIVDir = "~/.quicbaas/piv"

// localPIVConfig carries the CLI flag configuration required to build a
// local PIV session.
type localPIVConfig struct {
	// backend selects the go-xkms PIV backend: file | pkcs11 | tpm2.
	backend string

	// dir is the key/certificate root for the file backend.
	dir string

	// PIN is the PKCS#11 user PIN (pkcs11 backend only).
	PIN string `json:"pin,omitempty" yaml:"pin,omitempty"`

	// pkcs11Module is the PKCS#11 library path (pkcs11 backend only).
	pkcs11Module string

	// pkcs11Token is the PKCS#11 token label (pkcs11 backend only).
	pkcs11Token string
}

// localPIVSession is the client-local PIV seam shared by enrollment and
// login. Certificate reads the slot certificate; SignNonce signs the
// server-issued login nonce with the slot's private key (SHA-256 digest,
// the format go-xkms's PIVHardwareFactorVerifier verifies). Close releases
// the underlying storage.
type localPIVSession interface {
	Certificate(slot string) (*x509.Certificate, error)
	SignNonce(ctx context.Context, slot string, nonce []byte) ([]byte, error)
	Close() error
}

// newLocalPIVSessionFunc is a package-level seam so the enrollment and
// login plumbing can be unit-tested without local key material. The
// production default builds real go-xkms backends; tests replace it with a
// fake session. The seam never bypasses the xkms backends in production
// code.
var newLocalPIVSessionFunc = newLocalPIVSession

// newLocalPIVSession dispatches construction on the configured backend.
func newLocalPIVSession(cfg *localPIVConfig) (localPIVSession, error) {
	if cfg == nil {
		return nil, &InvalidPIVBackendError{Backend: ""}
	}
	switch cfg.backend {
	case "", localPIVBackendFile:
		return newFilePIVSession(cfg)
	case localPIVBackendPKCS11:
		return newPKCS11PIVSession(cfg)
	case localPIVBackendTPM2:
		// go-xkms ships no client-local TPM2 PIV certificate storage yet
		// (xkey's own tpm2 PIV storage reports the same); surface the
		// capability gap as a typed error instead of a partial wiring.
		return nil, &PIVLocalBackendUnsupportedError{
			Backend: localPIVBackendTPM2,
			Reason:  "go-xkms provides no client-local TPM2 PIV certificate storage",
		}
	default:
		return nil, &InvalidPIVBackendError{Backend: cfg.backend}
	}
}

// localPIVOwnsXKMS records that this process's xkms service singleton was
// initialized by the local PIV session, so a second session (e.g. factor
// rotate after add) may reuse it instead of failing the in-use guard.
var localPIVOwnsXKMS bool

// filePIVSession is the file-backed local PIV session: certificates in a
// go-xkms PIV file store under <dir>/piv, keys in the go-xkms software
// keystore rooted at <dir>.
type filePIVSession struct {
	store xkmssdk.PIVCertificateStorage
}

// newFilePIVSession assembles the file-backed session through the go-xkms
// SDK: file storage + software keystore (embedded service singleton) + PIV
// manager + backend resolver, mirroring xkey's ensurePIVInitialized.
func newFilePIVSession(cfg *localPIVConfig) (localPIVSession, error) {
	dir := cfg.dir
	if dir == "" {
		dir = defaultLocalPIVDir
	}
	dir = expandCanonicalHome(dir)
	if dir == "" {
		return nil, &PIVLocalSessionError{Op: "resolve dir", Cause: errHomeDirUnavailable}
	}

	// The embedded xkms service is a process-wide singleton. Refuse to
	// clobber one that something else initialized (e.g. the embedded
	// quicbaas transport running the full server in-process).
	if xkmssdk.ServiceIsInitialized() && !localPIVOwnsXKMS {
		return nil, &PIVLocalSessionError{Op: "init keystore", Cause: errXKMSServiceInUse}
	}
	if !xkmssdk.ServiceIsInitialized() {
		if _, err := xkmssdk.NewEmbeddedService(xkmssdk.EmbeddedServiceConfig{
			KeyDir:      dir,
			BackendName: localPIVXKMSBackendName,
		}); err != nil {
			return nil, &PIVLocalSessionError{Op: "init keystore", Cause: err}
		}
		localPIVOwnsXKMS = true
	}

	storageBackend, err := xkmssdk.NewFileStorageBackend(filepath.Join(dir, "piv"))
	if err != nil {
		return nil, &PIVLocalSessionError{Op: "init cert storage", Cause: err}
	}
	store, err := xkmssdk.NewPIVFileBackend(&xkmssdk.PIVFileStorageConfig{
		Backend:    storageBackend,
		DEREnabled: true,
		PEMEnabled: true,
	})
	if err != nil {
		return nil, &PIVLocalSessionError{Op: "init cert storage", Cause: err}
	}

	if err := initLocalPIVManager(localPIVXKMSBackendName, store); err != nil {
		return nil, err
	}
	return &filePIVSession{store: store}, nil
}

// initLocalPIVManager initializes the go-xkms PIV manager (idempotent),
// registers the store under the backend name, and installs the backend
// resolver so SignPIV resolves slot keys from the registered keystore.
func initLocalPIVManager(backendName string, store xkmssdk.PIVCertificateStorage) error {
	if err := xkmssdk.InitializePIV(&xkmssdk.PIVManagerConfig{
		Stores: map[string]xkmssdk.PIVCertificateStorage{backendName: store},
	}); err != nil {
		return &PIVLocalSessionError{Op: "init piv manager", Cause: err}
	}
	if err := xkmssdk.RegisterPIVStore(backendName, store); err != nil {
		return &PIVLocalSessionError{Op: "register piv store", Cause: err}
	}
	svc, err := xkmssdk.Get()
	if err != nil {
		return &PIVLocalSessionError{Op: "resolve xkms service", Cause: err}
	}
	if err := svc.InitPIVBackendResolver(); err != nil {
		return &PIVLocalSessionError{Op: "init piv backend resolver", Cause: err}
	}
	return nil
}

// Certificate reads the slot certificate from the file store.
func (s *filePIVSession) Certificate(slot string) (*x509.Certificate, error) {
	return localPIVCertificate(s.store, slot)
}

// SignNonce signs SHA-256(nonce) with the slot key held in the software
// keystore. The explicit sha256 selection matches go-xkms's
// PIVHardwareFactorVerifier, which always verifies over SHA-256(nonce).
func (s *filePIVSession) SignNonce(ctx context.Context, slot string, nonce []byte) ([]byte, error) {
	return localPIVSignNonce(ctx, localPIVXKMSBackendName, slot, nonce)
}

// Close releases the certificate store. The xkms singleton stays up: it is
// process-wide and other sessions in the same CLI invocation may reuse it.
func (s *filePIVSession) Close() error {
	return s.store.Close()
}

// localPIVCertificate validates the slot and reads its certificate from a
// PIV store. Shared by every backend session.
func localPIVCertificate(store xkmssdk.PIVCertificateStorage, slot string) (*x509.Certificate, error) {
	s := xkmssdk.PIVSlot(strings.ToLower(slot))
	if err := xkmssdk.ValidatePIVSlot(s); err != nil {
		return nil, &PIVLocalSessionError{Op: "validate slot", Cause: err}
	}
	cert, err := store.Retrieve(s)
	if err != nil {
		return nil, &PIVLocalSessionError{Op: "read certificate", Cause: err}
	}
	return cert, nil
}

// localPIVSignNonce signs the login nonce with the slot key resolved
// through the go-xkms PIV backend resolver. SHA-256 is forced because the
// server-side verifier always digests the nonce with SHA-256 regardless of
// key size.
func localPIVSignNonce(ctx context.Context, backendName, slot string, nonce []byte) ([]byte, error) {
	resp, err := xkmssdk.SignPIV(ctx, &xkmssdk.PIVSignRequest{
		Backend:       backendName,
		Slot:          strings.ToLower(slot),
		Payload:       nonce,
		HashAlgorithm: "sha256",
	})
	if err != nil {
		return nil, &PIVLocalSessionError{Op: "sign nonce", Cause: err}
	}
	if resp == nil || len(resp.Signature) == 0 {
		return nil, &PIVLocalSessionError{Op: "sign nonce", Cause: errEmptyPIVSignature}
	}
	return resp.Signature, nil
}
